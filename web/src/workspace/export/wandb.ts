/**
 * Weights & Biases export: a small Python file that puts the plan into a W&B run, so the run's
 * own charts sit beside what Preflight predicted. The knobs go in as the run's config; each
 * readout goes in the run's summary as `preflight/<target>/{point,lo,hi}_<unit>` with its status,
 * and an abstaining readout carries its status only. No key is in the file: the visitor's own
 * `wandb.init()` logs in as usual. Every number is the plan's (plan.ts), never recomputed here.
 * A sample's numbers are illustrative, and the file says so, in its text and in the run's summary.
 */
import type { ExportPlan } from "./plan";

export const WANDB_FILE = "preflight_wandb.py";

/** The plan as JSON that can sit in a Python raw string: no quote or backslash can close it. */
function payload(plan: ExportPlan, illustrative: boolean): string {
	const data = {
		title: plan.title,
		lens: plan.lens,
		illustrative,
		share_url: plan.shareUrl,
		gpu: plan.gpu,
		config: plan.config,
		changes: plan.changes.map((c) => ({ knob: c.knobId, from: c.from, to: c.to, needs_code: c.needsCode })),
		code_changes_verified: plan.codeChangesVerified,
		// A unit like "tokens/s" would open a W&B section at the slash: summary keys use "tokens_s".
		readouts: plan.readouts.map((r) => ({ target: r.targetId, unit: r.unit.replace(/[^A-Za-z0-9]+/g, "_"), status: r.status, point: r.point, lo: r.lo, hi: r.hi })),
	};
	// No quote may appear inside the raw string, so a title's apostrophe is written as JSON's \u0027;
	// the payload always ends in "}", so no backslash can sit against the closing quotes.
	return JSON.stringify(data, null, "\t").replace(/'/g, "\\u0027");
}

export function wandbFile(plan: ExportPlan, illustrative = false): string {
	const sample = illustrative
		? "\nFrom a Preflight sample: its numbers are illustrative, not measured on your job, and the run's\nsummary says so (preflight/illustrative).\n"
		: "";
	const link = plan.shareUrl ? "The run's config also gets the link to this Preflight record: anyone who can see the run can\nopen the record with it.\n" : "";
	return `"""Preflight's plan for this run, for Weights & Biases. Generated by Preflight; no key inside.
${sample}
    import wandb
    import preflight_wandb

    run = wandb.init(project="my-project", config=preflight_wandb.CONFIG)
    preflight_wandb.attach(run)

attach() writes Preflight's predictions into the run's summary as
preflight/<readout>/point_<unit>, lo_<unit> and hi_<unit> (the 90% interval), with
preflight/<readout>/status. A readout Preflight wouldn't predict has a status and no numbers.
${link}"""

import json

PLAN = json.loads(r'''${payload(plan, illustrative)}''')

# The knob values Preflight planned, as the run's config.
CONFIG = dict(PLAN["config"])


def attach(run):
    """Add the plan to a wandb Run: where it came from in the config, the readouts in the summary."""
    run.config.update(
        {"preflight": {k: PLAN[k] for k in ("title", "lens", "illustrative", "share_url", "gpu", "changes", "code_changes_verified")}},
        allow_val_change=True,
    )
    run.summary["preflight/illustrative"] = PLAN["illustrative"]
    for r in PLAN["readouts"]:
        key = "preflight/" + r["target"]
        run.summary[key + "/status"] = r["status"]
        for part in ("point", "lo", "hi"):
            if r[part] is not None:
                run.summary[key + "/" + part + "_" + r["unit"]] = r[part]
    run.tags = (*tuple(run.tags or ()), "preflight")
    return run
`;
}
