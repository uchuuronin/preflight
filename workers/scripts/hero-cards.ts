/**
 * Renders the hero records' cards ahead of time (hero-cards.json), with the same code the /card
 * route uses, into static/cards/<token>.png, and writes functions/_card/hero.ts, the list of tokens
 * that have one. Served as plain files, these preview with an image on the Workers Free plan, where
 * rendering per request would pass the 10 ms CPU limit. Run with `npm run hero-cards`; with
 * `--check` it renders in memory and exits 1 if a committed card or hero.ts is out of date.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve, sep } from "node:path";
import { headline, type RecordLike } from "../functions/_card/headline";
import { renderPng } from "../functions/_card/render";
import { CARD_W, cardSvg } from "../functions/_card/svg";

const workers = process.env.WORKERS_DIR as string;
const repo = join(workers, "..");
const check = process.argv.includes("--check");
const card = join(workers, "functions", "_card");
const wasm = readFileSync(join(card, "vendor", "resvg", "index_bg.wasm"));
const fonts = ["InstrumentSans-400", "InstrumentSans-600", "InstrumentSerif-400", "JetBrainsMono-500"].map(
	(f) => new Uint8Array(readFileSync(join(card, "fonts", `${f}.bin`))),
);
const list = JSON.parse(readFileSync(join(workers, "hero-cards.json"), "utf8")) as { cards: Array<{ link_id: string; record: string }> };

let stale = 0;
const cardsDir = join(workers, "static", "cards");
mkdirSync(cardsDir, { recursive: true });
for (const c of list.cards) {
	if (!/^[A-Za-z0-9_-]{8,64}$/.test(c.link_id)) throw new Error(`bad share token: ${c.link_id}`);
	const recordPath = resolve(repo, c.record);
	if (!recordPath.startsWith(resolve(repo) + sep)) throw new Error(`record outside the repository: ${c.record}`);
	const record = JSON.parse(readFileSync(recordPath, "utf8")) as RecordLike;
	// No host on a pre-rendered card: it is built before the live host is known.
	const png = await renderPng(cardSvg(headline(record), ""), wasm, fonts, CARD_W);
	const out = join(cardsDir, `${c.link_id}.png`);
	if (check) {
		if (!existsSync(out) || !Buffer.from(png).equals(readFileSync(out))) {
			console.error(`out of date: static/cards/${c.link_id}.png`);
			stale++;
		}
	} else writeFileSync(out, png);
}

// A card file with no entry in hero-cards.json would still be deployed: refuse it.
const listed = new Set(list.cards.map((c) => `${c.link_id}.png`));
for (const f of readdirSync(cardsDir)) {
	if (!listed.has(f)) {
		console.error(`not in hero-cards.json: static/cards/${f}`);
		stale++;
	}
}
if (stale && !check) process.exit(1);

const tokens = list.cards.map((c) => `\t"${c.link_id}", // gitleaks:allow (a share token: the public link id, not a secret)`).join("\n");
const hero = `/** Generated by scripts/hero-cards.ts from hero-cards.json: share tokens with a pre-rendered card at /cards/<token>.png. */\nexport const HERO_CARDS: ReadonlySet<string> = new Set([\n${tokens}\n]);\n`;
const heroPath = join(card, "hero.ts");
if (check) {
	if (!existsSync(heroPath) || readFileSync(heroPath, "utf8") !== hero) {
		console.error("out of date: functions/_card/hero.ts");
		stale++;
	}
	if (stale) process.exit(1);
	console.log(`${list.cards.length} hero card(s) up to date`);
} else {
	writeFileSync(heroPath, hero);
	console.log(`rendered ${list.cards.length} hero card(s) into static/cards`);
}
