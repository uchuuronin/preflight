"""Fit the reserved-pool margin on the corpus (Chiya, Nov 3, item 2): reserved over allocated peak, by family and size.

	uv run python scripts/fit_reserved_margin.py <preflight-corpus-0.4.0.jsonl.gz> python/preflight/engine/_reserved_margin.py

Rows: the corpus's `calibration` split only (no A100 or MI300X holdout, no synthetic LoRA family, never the zoo), status
ok, both peaks recorded. For each (family, size bucket) with at least MIN_ROWS rows, and for each family over all sizes,
the median and the 90th percentile of peak_reserved / peak_allocated. The engine (`engine.memory_reserved`, off) raises a
prediction only where its own probes' ratio is below these.
"""

from __future__ import annotations

import gzip
import json
import sys
from collections import defaultdict

MIN_ROWS = 20  # guess: fewer rows and a 90th percentile is one or two rows
SIZES = ((1e7, "<10M"), (1e8, "<100M"), (1e9, "<1B"), (float("inf"), ">=1B"))


def size_bucket(n_params: float) -> str:
	return next(name for top, name in SIZES if n_params < top)


def quantile(v: list[float], q: float) -> float:
	v = sorted(v)
	return v[min(len(v) - 1, int(q * (len(v) - 1)))]


def fit(path: str) -> dict:
	by: dict = defaultdict(list)
	fam: dict = defaultdict(list)
	with gzip.open(path, "rt") as fh:
		rows = [json.loads(line) for line in fh]
	for r in rows:
		if (
			r.get("split") != "calibration"
			or r.get("kind") not in ("kernels", "hf")
			or r.get("status") != "ok"
		):
			continue
		m = r.get("memory") or {}
		a, res = m.get("peak_allocated"), m.get("peak_reserved")
		if not a or not res or not r.get("n_params"):
			continue
		f = "hf" if r["kind"] == "hf" else (r.get("config") or {}).get("family")
		by[(f, size_bucket(r["n_params"]))].append(res / a)
		fam[f].append(res / a)

	def cell(v: list[float]) -> dict:
		return {"median": round(quantile(v, 0.5), 4), "q90": round(quantile(v, 0.9), 4), "n": len(v)}

	return {
		"$comment": "reserved / allocated peak, corpus calibration split, five timed steps per config (fit_reserved_margin.py)",
		"by_size": {f"{f}|{s}": cell(v) for (f, s), v in sorted(by.items()) if len(v) >= MIN_ROWS},
		"by_family": {f: cell(v) for f, v in sorted(fam.items())},
	}


if __name__ == "__main__":
	out = fit(sys.argv[1])
	with open(sys.argv[2], "w") as fh:  # a module, as _calibration_table.py: the engine also runs in Pyodide
		fh.write(
			f'"""Generated by scripts/fit_reserved_margin.py from {sys.argv[1].split("/")[-1]}; do not edit."""\n\n'
		)
		fh.write(f"MARGINS = {json.dumps(out, indent=1)}\n")
	print(json.dumps(out, indent=1))
